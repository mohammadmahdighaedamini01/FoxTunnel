private val EXTRA_ROOT_PEMS = listOf(GLOBALSIGN_ROOT_E46_PEM, GLOBALSIGN_ROOT_R46_PEM)

/**
 * Trust managers that trust everything the system already trusts PLUS the extra roots above.
 * Only those specific roots are added; no certificate is blindly accepted, and hostname
 * verification keeps working because the platform's own TrustManagerFactory is still used.
 */
internal fun buildTrustManagersWithExtraRoots(): Array<TrustManager> {
    val merged = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }

    runCatching {
        val system = KeyStore.getInstance("AndroidCAStore").apply { load(null, null) }
        val aliases = system.aliases()
        while (aliases.hasMoreElements()) {
            val alias = aliases.nextElement()
            system.getCertificate(alias)?.let { merged.setCertificateEntry(alias, it) }
        }
    }.onFailure {
        AppLogger.w(TAG, "could not read the system CA store (${it.message}); using default trust only")
        return defaultTrustManagers()
    }

    val factory = CertificateFactory.getInstance("X.509")
    EXTRA_ROOT_PEMS.forEachIndexed { i, pem ->
        runCatching {
            val cert = factory.generateCertificate(ByteArrayInputStream(pem.toByteArray(Charsets.US_ASCII)))
                as X509Certificate
            merged.setCertificateEntry("foxtunnel-extra-$i", cert)
        }.onFailure { AppLogger.e(TAG, "failed to load bundled root #$i", it) }
    }

    val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
    tmf.init(merged)
    return tmf.trustManagers
}

private fun defaultTrustManagers(): Array<TrustManager> {
    val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
    tmf.init(null as KeyStore?)
    return tmf.trustManagers
}
